#[test]
fn precision_marker_is_zero_sized() {
    assert_eq!(core::mem::size_of::<Pi<0>>(), 0);
    assert_eq!(core::mem::size_of::<Pi<40>>(), 0);
}

#[test]
fn decimal_representation_has_bounded_storage() {
    assert_eq!(core::mem::size_of_val(&Pi::<0>::truncated()), 1);
    assert_eq!(core::mem::size_of_val(&Pi::<40>::truncated()), 41);
}
