use perfect_pi::{MAX_DECIMAL_PLACES, Pi};

macro_rules! assert_case {
    ($d:literal, $truncated:literal, $rounded:literal) => {{
        assert_eq!(Pi::<$d>::decimal_places(), $d);
        assert_eq!(Pi::<$d>::truncated().to_string(), $truncated);
        assert_eq!(Pi::<$d>::round_nearest_even().to_string(), $rounded);
    }};
}

